/** Tunables used to derive a character's normal attacks from its body size and archetype. */
export interface NormalsProfile {
  /** Horizontal reach multiplier (1 = average). */
  reach: number;
  /** Extra startup frames added to every normal (slow heavy characters). */
  startupOffset: number;
  /** Damage multiplier applied to the baseline numbers. */
  damage: number;
  /** Height of the standing torso center, used to align hitboxes. */
  torsoY: number;
  headY: number;
  legY: number;
  lightEffect: HitEffect;
  heavyEffect: HitEffect;
  /** Attack ids the character may cancel normals into (specials/super). */
  specialCancels: string[];
}

const box = (x: number, y: number, w: number, h: number): Rect => ({ x, y, w, h });

