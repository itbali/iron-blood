/** Shared defaults for every attack; individual fields are overridden by the builders. */
export const baseAttack = (partial: Partial<AttackData> & Pick<AttackData, 'id' | 'name' | 'anim' | 'input' | 'category'>): AttackData => ({
  startup: 6,
  active: 3,
  recovery: 10,
  damage: 50,
  hitstun: 14,
  blockstun: 10,
  knockback: 5,
  pushback: 5,
  hitLevel: 'mid',
  hitboxes: [],
  hitStop: HITSTOP_LIGHT,
  effect: 'spark',
  sound: 'punch',
  meterGain: 30,
  chip: 0,
  ...partial,
});

